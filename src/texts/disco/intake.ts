// Сбор песен. Вводное — от организаторов («мы»), о боте — в третьем лице; голоса — после строки бота.
// Причины отказа стоят в строках списка песен — без голосов. Под списком уведомление и вопрос
// идут отдельными абзацами, у каждого свой голос в конце.

// Вводное: голос может быть у каждого абзаца, но вариантов без голоса столько же, сколько с голосом, —
// голос выпадает примерно в половине абзацев, все сразу — редко.
function orPlain<T>(plain: T, voiced: T[]): T[] {
  return [...voiced, ...voiced.map(() => plain)];
}

