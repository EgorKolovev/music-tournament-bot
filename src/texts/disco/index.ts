// Стиль «Диско» — по Disco Elysium. Бот говорит как обычно, а следом вклиниваются голоса навыков —
// внутренние голоса самого участника, как у Гарри: «ВНУТРЕННЯЯ ИМПЕРИЯ — …», иногда с проверкой
// «ЛОГИКА [Легко: провал] — …». У фразы несколько вариантов в разных голосах, поэтому на разные
// события выпадают разные голоса. Без мата.
//
// Как вставлять голос:
// - Сначала строка бота — слово в слово как в основном стиле, голос — с новой строки после неё.
// - Голос — мысль участника, а не слова бота: не просит ничего нажать, не говорит «пришлю» или «я умею»,
//   не благодарит и не поздравляет за бота. Всё, что человеку нужно знать, — в строке бота.
// - Голос — в конце сообщения или своего абзаца, не между строками бота. Если код склеивает сообщение
//   из нескольких фраз, голос — у последней (у finalWhen, а не у finalistCheer).
// - Один голос на сообщение. Вводное к сбору — исключение: голос может быть у каждого абзаца, но у
//   каждого столько же вариантов без голоса, чтобы все сразу выпадали редко.
// - Без голосов: служебные строки (счёт, заголовки, строки панели матча, причины отказа в списке песен),
//   сводки /status и /matches, подсказки над кнопками. В тостах — обычный текст; голос — только если
//   его реплика сама передаёт смысл («ВНУТРЕННЯЯ ИМПЕРИЯ — Жребий ещё не брошен»).
// - Один образ — в одном месте: хлопнувшая дверь, ставни, «отзвучал» не кочуют по фразам.
//
// Голоса и их характер:
//   ЛОГИКА — сухие выводы; ЭНЦИКЛОПЕДИЯ — бесполезные факты; РИТОРИКА — формулировки и споры;
//   ДРАМА — театр: «браво», «занавес», «акт»; без «сир» и «вы» — с участником на «ты» и без рода;
//   КОНЦЕПТУАЛИЗАЦИЯ — песни как искусство; ВОСПРИЯТИЕ (СЛУХ) — звук;
//   ВНУТРЕННЯЯ ИМПЕРИЯ — мистика, вещи живые; ТРЕПЕТ — голос города; ЭМПАТИЯ — чувства других;
//   АВТОРИТЕТ — власть, судейство; ВНУШЕНИЕ — уговорить; СИЛА ВОЛИ — поддержка; СТОЙКОСТЬ — терпеть;
//   БОЛЕВОЙ ПОРОГ — боль поражений; СУМРАК — страх и азарт; ЭЛЕКТРОХИМИЯ — ещё, ещё;
//   ЭКВИЛИБРИСТИКА — красиво; САМООБЛАДАНИЕ — спокойствие; СКОРОСТЬ РЕАКЦИИ — быстрее.
// Трепет — лиричный: ветер с залива, мокрая мостовая, фонари, ставни; не сухой «город сделал то-то»
// и не подпись к тексту бота.
// Иногда сквозь Трепет говорит не участник, а внешняя сущность (в игре это женский голос: «Я Ревашоль…»,
// «Я холодная. Я умираю»): называет себя чем-то большим — город, залив, ветер, ночь, дождь, улица —
// короткими фразами, в настоящем времени. Только в больших моментах: начало сбора, выход в финал,
// конец турнира, вылет из отбора, последний шаг выхода. В остальных местах Трепет рассказывает со стороны.
// Род у сущности может быть женский; к участнику — без рода.
// Электрохимия — голос тела и удовольствия: дофамин, мурашки, азарт, «тело хочет ещё»; без веществ.
// Логика — короткий вывод («Нет пар — нет матчей»), изредка и где она смешная; сухой факт — без голоса.
// Чаще всего — Трепет и Внутренняя империя.

